static unsigned
find_bytes (const char *data, unsigned len, unsigned start, const char *text)
{
  unsigned n = strlen (text);
  if (n > len) return UINT_MAX;
  for (unsigned i = start; i <= len - n; i++)
    if (!memcmp (data + i, text, n)) return i;
  return UINT_MAX;
}

static unsigned
read_unsigned (const char *data, unsigned len, unsigned pos)
{
  unsigned value = 0;
  assert (pos < len && data[pos] >= '0' && data[pos] <= '9');
  while (pos < len && data[pos] >= '0' && data[pos] <= '9')
    value = value * 10 + data[pos++] - '0';
  return value;
}

static void
check_stream (const char *data, unsigned len, unsigned object,
              const unsigned char *expected, unsigned expected_len, hb_bool_t pixels)
{
  unsigned length = find_bytes (data, len, object, "/Length ");
  unsigned stream = find_bytes (data, len, object, "stream\n");
  assert (length < stream && stream < len);
  unsigned stream_len = read_unsigned (data, len, length + 8);
  stream += 7;
  assert (stream_len <= len - stream);
  if (pixels && find_bytes (data, len, object, "/Filter /FlateDecode") < stream)
  {
    unsigned char *decoded = malloc (expected_len);
    assert (decoded);
    uLongf decoded_len = expected_len;
    assert (uncompress (decoded, &decoded_len, (const Bytef *) data + stream, stream_len) == Z_OK);
    assert (decoded_len == expected_len && !memcmp (decoded, expected, expected_len));
    free (decoded);
  }
  else
  {
    assert (stream_len == expected_len);
    assert (!memcmp (data + stream, expected, expected_len));
  }
}

static hb_blob_t *
render_png (const unsigned char *png, unsigned len, int64_t budget,
            hb_vector_paint_t **paint_out)
{
  hb_vector_paint_t *paint = hb_vector_paint_create_or_fail (HB_VECTOR_FORMAT_PDF);
  assert (paint);
  hb_paint_funcs_t *funcs = hb_vector_paint_get_funcs (paint);
  assert (hb_paint_set_budget (funcs, paint, budget));
  hb_glyph_extents_t ext = {0, 50, 30, -50};
  hb_vector_paint_set_glyph_extents (paint, &ext);
  hb_blob_t *image = hb_blob_create ((const char *) png, len,
                                   HB_MEMORY_MODE_READONLY, NULL, NULL);
  hb_paint_image (funcs, paint, image, 3, 5, HB_PAINT_IMAGE_FORMAT_PNG, 0, &ext);
  hb_blob_destroy (image);
  *paint_out = paint;
  return hb_vector_paint_render (paint);
}

static void
check_alpha_png (const unsigned char *png, unsigned png_len,
                 const unsigned char *color, unsigned color_len,
                 const unsigned char *alpha, unsigned alpha_len,
                 const char *color_space)
{
  hb_vector_paint_t *paint;
  hb_blob_t *pdf = render_png (png, png_len, HB_BUDGET_DEFAULT, &paint);
  assert (pdf);
  unsigned len;
  const char *data = hb_blob_get_data (pdf, &len);
  unsigned smask = find_bytes (data, len, 0, "/SMask ");
  assert (smask != UINT_MAX);
  unsigned mask_id = read_unsigned (data, len, smask + 7);
  char object[32];
  snprintf (object, sizeof (object), "%u 0 obj\n", mask_id);
  unsigned mask = find_bytes (data, len, 0, object);
  assert (mask != UINT_MAX);
  unsigned primary = 0, cursor = 0;
  while (cursor < smask)
  {
    unsigned next = find_bytes (data, len, cursor, "/Subtype /Image");
    if (next >= smask) break;
    primary = next;
    cursor = next + 1;
  }
  check_stream (data, len, primary, color, color_len, strcmp (color_space, "/Indexed /DeviceRGB") != 0);
  check_stream (data, len, mask, alpha, alpha_len, 1);
  unsigned color_pos = find_bytes (data, len, primary, color_space);
  assert (color_pos < find_bytes (data, len, primary, "stream\n"));
  hb_blob_destroy (pdf);
  hb_vector_paint_destroy (paint);
}

static void
check_rejected_png (const unsigned char *png, unsigned png_len, int64_t budget)
{
  hb_vector_paint_t *paint;
  hb_blob_t *pdf = render_png (png, png_len, budget, &paint);
  if (pdf)
  {
    unsigned len;
    const char *data = hb_blob_get_data (pdf, &len);
    assert (find_bytes (data, len, 0, "/Subtype /Image") == UINT_MAX);
    hb_blob_destroy (pdf);
  }
  hb_vector_paint_destroy (paint);
}

static void
write_u32 (unsigned char *p, unsigned value)
{
  p[0] = value >> 24;
  p[1] = value >> 16;
  p[2] = value >> 8;
  p[3] = value;
}

static void
check_compressed_input_budget (void)
{
  /* One RGBA pixel preceded by 128 empty, nonfinal stored DEFLATE blocks.
   * Decoding must charge for those blocks as well as the five output bytes. */
  unsigned char png[73 + 128 * 5] = {0};
  unsigned idat_len = sizeof (png) - 57;
  memcpy (png, rgba_png, 33);
  write_u32 (png + 16, 1);
  write_u32 (png + 20, 1);
  write_u32 (png + 29, crc32 (0, png + 12, 17));
  write_u32 (png + 33, idat_len);
  memcpy (png + 37, "IDAT", 4);
  unsigned char *p = png + 41;
  *p++ = 0x78; *p++ = 0x01; /* zlib header */
  for (unsigned i = 0; i < 128; i++)
  {
    *p++ = 0; *p++ = 0; *p++ = 0; *p++ = 255; *p++ = 255;
  }
  *p++ = 1; *p++ = 5; *p++ = 0; *p++ = 250; *p++ = 255;
  const unsigned char pixel[] = {0, 20, 100, 200, 128};
  memcpy (p, pixel, sizeof (pixel)); p += sizeof (pixel);
  write_u32 (p, adler32 (1, pixel, sizeof (pixel))); p += 4;
  write_u32 (p, crc32 (0, png + 37, idat_len + 4)); p += 4;
  memcpy (p, rgba_png + sizeof (rgba_png) - 12, 12);

  check_alpha_png (png, sizeof (png), pixel + 1, 3, pixel + 4, 1, "/DeviceRGB");
  check_rejected_png (png, sizeof (png), 10);
}

int
main (void)
{
  check_compressed_input_budget ();
  check_alpha_png (rgba_png, sizeof (rgba_png), rgba_color, sizeof (rgba_color),
                   rgba_alpha, sizeof (rgba_alpha), "/DeviceRGB");
  check_alpha_png (rgba_palette_png, sizeof (rgba_palette_png), rgba_color, sizeof (rgba_color),
                   rgba_alpha, sizeof (rgba_alpha), "/DeviceRGB");
  check_alpha_png (gray_alpha_png, sizeof (gray_alpha_png), gray_alpha_color, sizeof (gray_alpha_color),
                   gray_alpha_alpha, sizeof (gray_alpha_alpha), "/DeviceGray");
  check_alpha_png (indexed_png, sizeof (indexed_png), indexed_color, sizeof (indexed_color),
                   indexed_alpha, sizeof (indexed_alpha), "/Indexed /DeviceRGB");
  unsigned char uniform_color[20 * 20 * 3], uniform_alpha[20 * 20];
  for (unsigned i = 0; i < 20 * 20; i++)
  {
    uniform_color[i * 3] = 20;
    uniform_color[i * 3 + 1] = 100;
    uniform_color[i * 3 + 2] = 200;
    uniform_alpha[i] = 128;
  }
  check_alpha_png (uniform_png, sizeof (uniform_png), uniform_color, sizeof (uniform_color),
                   uniform_alpha, sizeof (uniform_alpha), "/DeviceRGB");
  check_rejected_png (invalid_filter_png, sizeof (invalid_filter_png), HB_BUDGET_DEFAULT);
  check_rejected_png (rgba_png, sizeof (rgba_png), 1);

  unsigned char oversized[sizeof (rgba_png)];
  memcpy (oversized, rgba_png, sizeof (oversized));
  memset (oversized + 16, 0xFF, 8); /* IHDR dimensions cannot wrap allocation sizes. */
  check_rejected_png (oversized, sizeof (oversized), HB_BUDGET_DEFAULT);
  return 0;
}
